'use strict';

/**
 * stateDir — каталог ИЗМЕНЯЕМОГО СОСТОЯНИЯ инсталляции.
 *
 * ЗАЧЕМ ОН ПОНАДОБИЛСЯ. Часть состояния системы принципиально не может лежать ни в
 * репозитории, ни в базе: публичный ключ шифрования копий и реестр внешних хранилищ
 * (`backupSettings.json`), сами файлы копий (`backups/`), флаг режима обслуживания.
 * Всё это относится к КОНКРЕТНОЙ МАШИНЕ, а не к коду и не к данным, и до сих пор
 * складывалось в корень проекта — потому что «корень проекта» и «машина» казались
 * одним и тем же местом.
 *
 * В контейнерном развёртывании они перестают быть одним местом. Каталог проекта там —
 * это слой образа: `docker rm -f` + `docker run` на каждом деплое создаёт файловую
 * систему заново, и всё, что приложение записало в неё за время работы, исчезает.
 * Потеря тихая: система поднимается штатно, форма показывает пустые поля, и узнаёшь о
 * ней либо когда сорвалась ночная выгрузка, либо когда понадобилось восстановление, —
 * то есть в худший из возможных моментов.
 *
 * ЧТО ЗДЕСЬ ЕСТЬ. Одна точка, отвечающая на вопрос «где у этой инсталляции состояние».
 * Умолчание — корень проекта: для тех, у кого проект и есть машина (разработка,
 * обычная установка на сервер без контейнера), ничего не меняется. Переменная
 * окружения `MOS_STATE_DIR` переносит состояние в каталог, переживающий пересоздание
 * контейнера (том Docker), — и это единственное, что требуется от развёртывания.
 *
 * ПОЧЕМУ НЕ «ПРОСТО СМОНТИРОВАТЬ ТОМ В КОРЕНЬ ПРОЕКТА». Потому что в корне проекта
 * лежит КОД, приезжающий из образа. Том, наложенный поверх него, скроет код; том,
 * наложенный на подкаталог, разведёт состояние и код только для одного подкаталога, а
 * файлы настроек лежат рядом с `index.js`. Отдельный каталог состояния — это то же
 * самое разделение, но объявленное в приложении, а не подстроенное монтированием.
 *
 * @module stateDir
 */

const fs = require('fs');
const path = require('path');

/** Имя переменной окружения. Вынесено, чтобы её можно было назвать в диагностике. */
const ENV_VAR = 'MOS_STATE_DIR';

let _announced = false;

function projectRoot() {
    if (process.env.PROJECT_ROOT) return process.env.PROJECT_ROOT;
    try {
        const r = require('./globalServerContext').getProjectRoot();
        if (r) return r;
    } catch (e) { /* контекст может быть ещё не поднят — воркер */ }
    return process.cwd();
}

/**
 * Абсолютный путь каталога состояния.
 *
 * Относительное значение переменной разрешается от корня проекта — так `MOS_STATE_DIR=state`
 * означает понятное «подкаталог рядом с кодом», а не зависящее от способа запуска
 * место относительно текущего каталога процесса.
 * @returns {string}
 */
function dir() {
    const custom = String(process.env[ENV_VAR] || '').trim();
    if (!custom) return projectRoot();
    return path.isAbsolute(custom) ? custom : path.join(projectRoot(), custom);
}

/** Отличается ли каталог состояния от корня проекта (то есть задан ли он явно). */
function isSeparate() {
    return path.resolve(dir()) !== path.resolve(projectRoot());
}

/**
 * Создать каталог состояния, если его нет, и один раз сказать в журнал, где он.
 *
 * Строка в журнале не декоративная: при разборе «куда делись ключи» первым делом
 * нужно знать, куда система их клала, а не куда их клал тот, кто настраивал деплой.
 * @returns {string} абсолютный путь
 */
function ensure() {
    const d = dir();
    if (!fs.existsSync(d)) fs.mkdirSync(d, { recursive: true });
    if (!_announced) {
        _announced = true;
        try {
            require('./log').info(`[state] Каталог состояния инсталляции: ${d}`
                + (isSeparate() ? '' : ` (умолчание — корень проекта; том задаётся ${ENV_VAR})`));
        } catch (e) { /* журнал может быть ещё не поднят */ }
    }
    return d;
}

/**
 * Путь к файлу состояния по имени.
 *
 * Если каталог состояния вынесен отдельно, а файл там ещё не появился, но лежит в
 * корне проекта — он переносится КОПИРОВАНИЕМ, однократно. Иначе включение
 * `MOS_STATE_DIR` на уже работающей инсталляции выглядело бы ровно как та авария,
 * которую эта переменная и должна предотвращать: ключ на месте, а система его не
 * видит. Оригинал не удаляется намеренно: перенос секрета не должен быть операцией,
 * после которой нечего откатывать.
 *
 * @param {string} name — имя файла (`backupSettings.json`) или подкаталога (`backups`)
 * @returns {string} абсолютный путь внутри каталога состояния
 */
function resolve(name) {
    const target = path.join(ensure(), name);
    if (!isSeparate()) return target;

    const legacy = path.join(projectRoot(), name);
    if (fs.existsSync(target) || !fs.existsSync(legacy)) return target;

    try {
        // Только файлы: каталог копий может весить гигабайты, и переносить его
        // молча при старте сервера нельзя — это делают руками, разово.
        if (!fs.statSync(legacy).isFile()) return target;
        fs.copyFileSync(legacy, target);
        require('./log').info(`[state] ${name} перенесён из корня проекта в ${target} (оригинал оставлен)`);
    } catch (e) {
        try { require('./log').warn(`[state] Перенос ${name} не выполнен: ${e.message}`); } catch (e2) {}
    }
    return target;
}

module.exports = { dir, resolve, ensure, isSeparate, projectRoot, ENV_VAR };
