'use strict';

/**
 * systemDataStrategies — РЕГИСТРАЦИЯ стратегий типов системных данных.
 *
 * Отдельный модуль, а не строчка в `index.js`, по одной причине: восстановление идёт в
 * ДОЧЕРНЕМ процессе (`restoreWorker.js`), и его граф зависимостей `index.js` не
 * содержит вовсе — воркер тянет `restoreFull` напрямую. Пока регистрация жила в
 * `index.js`, в главном процессе стратегии были, а в том единственном процессе, который
 * их исполняет, реестр оставался ПУСТЫМ. `applyAll` молча брал умолчание `carryOver`, и
 * пользователи вместо слияния получали `DELETE FROM users` в теневой схеме — падение на
 * первом же внешнем ключе, ссылающемся на пользователя (`Messenger_ChatMembers_userId_fkey`
 * и далее по списку). Симптом выглядел как «копия несовместима», хотя копия была цела.
 *
 * `systemData` по-прежнему не знает, какие типы бывают: он механизм. Знание живёт здесь,
 * а требование к вызывающим — простое и одно: тот, кто зовёт `applyAll`, обязан брать
 * модуль ОТСЮДА, а не из `./systemData` напрямую.
 *
 * @module backup/systemDataStrategies
 */

const systemData = require('./systemData');

systemData.registerStrategy('users_and_roles', require('./systemDataUsers').mergeUsers);
// Остальным типам («настройки копирования», «регламентные задания») отдельная
// стратегия не нужна: у них побеждает текущее целиком, а это и есть умолчание.

module.exports = systemData;
