'use strict';

/**
 * serviceFields — СЛУЖЕБНЫЙ РЕКВИЗИТ.
 *
 * Есть реквизиты, которые принадлежат не пользователю, а механизму: момент времени
 * документа (`seq`), состояние проведения (`postingState`), счётчик цепочки хешей в
 * журнале. Их заполняет ядро, человек их не вводит и в большинстве случаев не должен
 * даже видеть — но в схеме и в метаданных они обязаны быть, иначе их нечем читать.
 *
 * До этого механизма список «что не показывать» был один и захардкоженный: `UID` и
 * отметки времени Sequelize, перечисленные по имени в трёх разных местах. Каждый новый
 * системный реквизит требовал править эти три места, и пропуск одного из них выглядел
 * как «в автоформе появилось редактируемое поле seq» — ошибка, которую замечают не
 * сразу и не там, где она сделана.
 *
 * ОБЪЯВЛЕНИЕ. В определении поля (`db.json` или инъекция ядра):
 *
 *     "seq": { "type": "BIGINT", "service": true, ... }
 *
 * ЧТО ЭТО ЗНАЧИТ. Ровно одно: поле не попадает в АВТОМАТИЧЕСКИ построенный интерфейс —
 * ни полем автоформы записи, ни колонкой автосписка, ни колонкой табличной части.
 * Это НЕ право доступа и НЕ запрет на чтение: значение читается как обычно, и
 * рукописный лейаут вправе показать его намеренно (отладочный или административный
 * вид), просто назвав поле в своих колонках. Замок на запись — дело `immutable`, а не
 * этого признака: смешивать «не показываем» и «нельзя менять» нельзя, это разные
 * вопросы с разными ответами.
 *
 * ГДЕ ПРИМЕНЯЕТСЯ (все потребители — здесь, чтобы список не разъезжался):
 *   1. `globalServerContext.getTableMetadata` — кладёт признак в метаданные поля;
 *   2. `globalServerContext.getDataForTable` — автоколонки списка;
 *   3. `uniForm/server.js#buildTableFieldsFromModel` — автоформа записи и колонки
 *      табличной части.
 *
 * `UID` и отметки времени Sequelize остаются отдельным случаем: они есть у КАЖДОЙ
 * таблицы и не объявляются в `db.json` вовсе, поэтому пометить их негде — их имена
 * перечислены здесь (`ALWAYS_SERVICE`) и проверяются тем же предикатом.
 */

/**
 * Реквизиты, служебные всегда и у всех таблиц. Объявления у них нет — есть только имя.
 * `UID` в этом списке НЕ значит «не читать»: автоформа и так прятала его по имени,
 * теперь делает это по правилу.
 */
const ALWAYS_SERVICE = new Set(['createdAt', 'updatedAt', 'deletedAt']);

/**
 * Поле служебное?
 * @param {string} fieldName — имя реквизита
 * @param {object} [fieldDef] — его определение из `db.json` (если есть)
 * @returns {boolean}
 */
function isServiceField(fieldName, fieldDef) {
    if (ALWAYS_SERVICE.has(fieldName)) return true;
    return !!(fieldDef && fieldDef.service === true);
}

/**
 * Пометить поле служебным. Для инъекций ядра — чтобы признак ставился там же, где
 * создаётся сам реквизит, а не отдельным списком имён в третьем файле.
 * @param {object} fieldDef — определение поля (мутируется in-place)
 * @returns {object} оно же
 */
function markService(fieldDef) {
    if (fieldDef && typeof fieldDef === 'object') fieldDef.service = true;
    return fieldDef;
}

/**
 * Отфильтровать служебные из СПИСКА МЕТАДАННЫХ (элементы с `.name` и `.service`).
 * Ровно то, что нужно всем трём потребителям автогенерации.
 * @param {Array<object>} fields — метаданные полей (`getTableMetadata`)
 * @param {object} [opts] — `{ keepUID: true }` — оставить `UID` (он нужен данным формы);
 *   `{ keep: ['postingState'] }` — реквизиты, НАЗВАННЫЕ лейаутом явно: правило «не
 *   показывать» относится к автогенерации, а рукописный лейаут вправе показать
 *   служебное поле намеренно (колонка «Проведение» в журнале документов).
 * @returns {Array<object>}
 */
function withoutService(fields, opts = {}) {
    if (!Array.isArray(fields)) return fields;
    const keep = Array.isArray(opts.keep) ? opts.keep : [];
    return fields.filter(f => {
        if (!f) return false;
        if (f.name === 'UID') return !!opts.keepUID;
        if (keep.indexOf(f.name) !== -1) return true;
        return !f.service;
    });
}

module.exports = { ALWAYS_SERVICE, isServiceField, markService, withoutService };
